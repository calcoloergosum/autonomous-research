let server,browser;
const start=async(port)=>{
  server=spawn(python,['-m','arf.observer','--db',db,...(port?['--port',String(port)]:[])],{cwd:root,stdio:['ignore','pipe','pipe']});
  const data=await Promise.race([once(server.stdout,'data'),once(server,'exit').then(()=>{throw Error('observer exited')})]);
  return JSON.parse(String(data[0])).url;
};
const stop=async()=>{if(server&&server.exitCode===null){server.kill('SIGINT');await once(server,'exit');}};
const results=[];
