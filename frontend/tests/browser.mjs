// Offline real-browser journey; all spawned processes are owned and awaited.
import {chromium} from 'playwright';
import {spawn,execFileSync} from 'node:child_process';
import {once} from 'node:events';
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
const root=path.resolve('..'), python=path.join(root,'.venv/bin/python');
const dir=fs.mkdtempSync(path.join(root,'.local/vs005-browser.')), db=path.join(dir,'arf.db');
const fixture=JSON.parse(execFileSync(python,['-m','arf.decision_demo','--db',db],{cwd:root,encoding:'utf8'}));
