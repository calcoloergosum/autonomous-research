  await page.getByRole('button',{name:/^pinned-arrival pending/}).waitFor({timeout:12000});
  assert.equal(await page.locator('.checkpoint pre').innerText(),pinned);
  assert.ok((await page.locator('.comparison').innerText()).includes(later));
  assert.ok((await inspector.innerText()).includes('task / B'));
